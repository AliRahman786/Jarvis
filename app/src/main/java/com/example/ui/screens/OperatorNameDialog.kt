@Composable
fun OperatorNameDialog(
    viewModel: JarvisViewModel,
    onDismiss: () -> Unit
) {
    val accentColor = viewModel.getAccentColor()
    var nameInput by remember { mutableStateOf(viewModel.prefs.getUserName()) }

    Dialog(onDismissRequest = onDismiss) {
        Box(
            modifier = Modifier
                .fillMaxWidth()
                .clip(RoundedCornerShape(16.dp))
                .background(GlassCardBackground)
                .border(1.5.dp, accentColor.copy(alpha = 0.5f), RoundedCornerShape(16.dp))
                .padding(20.dp)
                .testTag("operator_name_dialog")
        ) {
            Column(modifier = Modifier.fillMaxWidth()) {
                // Header
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Box(
                            modifier = Modifier
                                .size(36.dp)
                                .clip(CircleShape)
                                .background(accentColor.copy(alpha = 0.15f))
                                .border(1.dp, accentColor, CircleShape),
                            contentAlignment = Alignment.Center
                        ) {
                            Icon(
                                imageVector = Icons.Default.Person,
                                contentDescription = "Operator",
                                tint = accentColor,
                                modifier = Modifier.size(20.dp)
                            )
                        }
                        Spacer(modifier = Modifier.width(10.dp))
                        Column {
                            Text(
                                text = "OPERATOR IDENTITY",
                                color = HologramTextBright,
                                fontSize = 15.sp,
                                fontFamily = FontFamily.Monospace,
                                fontWeight = FontWeight.Bold,
                                letterSpacing = 1.sp
                            )
                            Text(
                                text = "Primary User & Executive Boss",
                                color = HologramTextMuted,
                                fontSize = 11.sp
                            )
                        }
                    }

                    IconButton(onClick = onDismiss, modifier = Modifier.size(32.dp)) {
                        Icon(
                            imageVector = Icons.Default.Close,
                            contentDescription = "Close",
                            tint = HologramTextMuted
                        )
                    }
                }

                Spacer(modifier = Modifier.height(16.dp))

                OutlinedTextField(
                    value = nameInput,
                    onValueChange = { nameInput = it },
                    label = { Text("Operator Name / Call Sign", fontFamily = FontFamily.Monospace) },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth(),
                    colors = OutlinedTextFieldDefaults.colors(
                        focusedBorderColor = accentColor,
                        unfocusedBorderColor = accentColor.copy(alpha = 0.4f),
                        focusedTextColor = HologramTextBright,
                        unfocusedTextColor = HologramTextBright,
                        cursorColor = accentColor
                    )
                )

                Spacer(modifier = Modifier.height(16.dp))

                HudButton(
                    text = "CONFIRM & SAVE",
                    onClick = {
                        val clean = nameInput.trim().ifBlank { "Ali Rahman" }
                        viewModel.prefs.setUserName(clean)
                        viewModel.speakVoice("Identity updated. At your command, $clean.")
                        onDismiss()
                    },
                    accentColor = accentColor
                )

                Spacer(modifier = Modifier.height(8.dp))

                HudButton(
                    text = "CANCEL",
                    onClick = onDismiss,
                    accentColor = HologramTextDim
                )
            }
        }
    }
}
